import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

interface GameConfig {
  universe_id: number;
  name: string;
  module: string;
  min_tier: "free" | "premium";
  enabled: boolean;
}

const root = join(import.meta.dir, "..");

function sha256(input: string): string {
  return createHash("sha256").update(input).digest("hex");
}

const gamesConfig = JSON.parse(
  await readFile(join(root, "packages/hub/games.json"), "utf8"),
) as GameConfig[];

const core = await readFile(join(root, "packages/hub/init.luau"), "utf8");
const loader = await readFile(join(root, "packages/loader/loader.luau"), "utf8");
const windui = await readFile(join(root, "vendor/windui.lua"), "utf8");

const modules: Record<string, string> = {};
const moduleSha: Record<string, string> = {};
const games = [];

const hubHash = createHash("sha256").update(core);

for (const game of gamesConfig) {
  const source = await readFile(join(root, "packages/hub/games", game.module), "utf8");
  const digest = sha256(source);
  modules[game.module] = source;
  moduleSha[game.module] = digest;
  hubHash.update(digest);

  games.push({
    ...game,
    path: `/v1/modules/${game.module}`,
    sha256: digest,
    version: digest.slice(0, 8),
  });
}

const hubVersion = hubHash.digest("hex").slice(0, 10);
const manifest = { schema: 1, hub_version: hubVersion, games };

const output = [
  "// AUTO-GENERATED by scripts/gen-hub.ts. Do not edit by hand.",
  "",
  `export const HUB_VERSION = ${JSON.stringify(hubVersion)};`,
  "",
  `export const MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;`,
  "",
  `export const HUB_CORE = ${JSON.stringify(core)};`,
  "",
  `export const LOADER = ${JSON.stringify(loader)};`,
  "",
  `export const MODULES: Record<string, string> = ${JSON.stringify(modules)};`,
  "",
  `export const MODULE_SHA: Record<string, string> = ${JSON.stringify(moduleSha)};`,
  "",
  `export const WINDUI = ${JSON.stringify(windui)};`,
  "",
  `export const WINDUI_SHA = ${JSON.stringify(sha256(windui))};`,
  "",
].join("\n");

const target = join(root, "apps/worker/src/generated/hub.ts");
await mkdir(join(root, "apps/worker/src/generated"), { recursive: true });
await writeFile(target, output);

console.log(
  `generated hub ${hubVersion} · ${games.length} game(s) · ${(output.length / 1024).toFixed(0)} KiB`,
);
